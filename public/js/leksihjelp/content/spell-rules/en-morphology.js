/**
 * Spell-check rule: English Morphology — Irregular Overgeneration (priority 17).
 *
 * Flags tokens where a Norwegian student has applied a regular inflection
 * pattern (e.g. -ed, -s) to an irregular English verb or noun:
 *   childs -> children, eated -> ate, goed -> went
 *
 * Depends on the irregularForms Map built by vocab-seam-core.js (Phase 14).
 * Each Map key is a wrong regular form (lowercase); value is
 * { correct: string, type: 'past'|'plural', base: string }.
 *
 * Rule ID: 'en-morphology'
 */
(function () {
  'use strict';
  const host = typeof self !== 'undefined' ? self : globalThis;
  host.__lexiSpellRules = host.__lexiSpellRules || [];
  const { matchCase, escapeHtml } = host.__lexiSpellCore || {};

  // Double-plural forms: students sometimes add -s to an already-irregular
  // plural (childrens, mens, womens). These aren't generated by the
  // irregularForms builder (which derives from the singular base), so we
  // handle them inline with a small closed set.
  const DOUBLE_PLURALS = new Map([
    ['childrens', { correct: 'children', type: 'plural', base: 'child' }],
    ['mens', { correct: 'men', type: 'plural', base: 'man' }],
    ['womens', { correct: 'women', type: 'plural', base: 'woman' }],
    ['teeths', { correct: 'teeth', type: 'plural', base: 'tooth' }],
    ['feets', { correct: 'feet', type: 'plural', base: 'foot' }],
    ['mices', { correct: 'mice', type: 'plural', base: 'mouse' }],
    ['geeses', { correct: 'geese', type: 'plural', base: 'goose' }],
    ['oxens', { correct: 'oxen', type: 'plural', base: 'ox' }],
    ['peoples', { correct: 'people', type: 'plural', base: 'person' }],
  ]);

  const rule = {
    id: 'en-morphology',
    languages: ['en'],
    priority: 17,
    exam: {
      safe: true,
      reason: "Lookup-shaped grammar rule (en-morphology) — Chrome native parity confirmed in 33-03 audit: EN morphology typo bank — single-token lookup against irregular forms",
      category: "grammar-lookup",
    },
    severity: 'warning',
    explain: (finding) => {
      const fix = escapeHtml(finding.fix);
      const orig = escapeHtml(finding.original);
      if (finding.morphType === 'plural') {
        return {
          nb: `Uregelrett flertall — bruk <em>${fix}</em> i stedet for <em>${orig}</em>.`,
          nn: `Uregelrett fleirtal — bruk <em>${fix}</em> i staden for <em>${orig}</em>.`,
          en: `Irregular plural — use <em>${fix}</em> instead of <em>${orig}</em>.`,
        };
      }
      return {
        nb: `Uregelrett fortidsform — bruk <em>${fix}</em> i stedet for <em>${orig}</em>.`,
        nn: `Uregelrett fortidsform — bruk <em>${fix}</em> i staden for <em>${orig}</em>.`,
        en: `Irregular past tense — use <em>${fix}</em> instead of <em>${orig}</em>.`,
      };
    },
    check(ctx) {
      const { tokens, vocab, cursorPos } = ctx;
      const irregularForms = vocab.irregularForms;
      if (!irregularForms || irregularForms.size === 0) return [];

      const out = [];

      for (let i = 0; i < tokens.length; i++) {
        const t = tokens[i];
        if (cursorPos != null && cursorPos >= t.start && cursorPos <= t.end + 1) continue;

        const lower = t.word;
        const entry = irregularForms.get(lower) || DOUBLE_PLURALS.get(lower);
        if (!entry) continue;
        // Ordbank sweep 2026-07: the derived error-form table collides with
        // REAL words — be+ed = "bed" (a noun; 19 clean-text firings on "go to
        // bed"), giraffe's -fe→-ves rule made correct "giraffes" flag, "bus
        // stops" hit a stop-plural entry. A blanket validWords gate is NOT
        // usable: the wordfreq-derived list contains genuinely-erroneous
        // corpus forms (taked, catched, mans …), so it would kill the rule's
        // core catches — curated real-word homographs only.
        const REAL_WORD_HOMOGRAPHS = new Set(['bed', 'giraffes', 'stops',
          'fishes', 'saw', 'left', 'found', 'ground', 'felt', 'rose', 'lay']);
        if (REAL_WORD_HOMOGRAPHS.has(lower)) continue;
        // 'lied' is the CORRECT past of lie-as-deceive ("he had lied to
        // her"); only lie-as-recline is irregular (lay/lain). The deceive
        // sense governs to/about.
        if (lower === 'lied' && tokens[i + 1] &&
            (tokens[i + 1].word === 'to' || tokens[i + 1].word === 'about')) continue;

        const fix = matchCase ? matchCase(t.display, entry.correct) : entry.correct;

        out.push({
          rule_id: 'en-morphology',
          morphType: entry.type,
          priority: rule.priority,
          start: t.start,
          end: t.end,
          original: t.display,
          fix: fix,
          suggestion: fix,
          message: entry.type === 'plural'
            ? `Uregelrett flertall: «${t.display}» skal være «${fix}».`
            : `Uregelrett fortid: «${t.display}» skal være «${fix}».`,
        });
      }
      return out;
    },
  };

  host.__lexiSpellRules.push(rule);
  if (typeof module !== 'undefined' && module.exports) module.exports = rule;
})();
